"""
report.py
=========
One-page branded PDF brief generator for AgriTrue (pure-Python via fpdf2).

Charts are drawn natively with fpdf primitives (rectangles/text) rather than rendered
images, so the report generates anywhere with no headless-browser or image dependency.

Public functions return PDF bytes, ready for Streamlit's st.download_button.
"""

from __future__ import annotations

from typing import Optional

from fpdf import FPDF

# UNEP-ish palette (R,G,B)
GREEN = (42, 157, 143)
DARK = (38, 70, 83)
RED = (209, 73, 91)
SAND = (233, 196, 106)
GREY = (110, 110, 110)


class _Brief(FPDF):
    def header(self):
        self.set_fill_color(*DARK)
        self.rect(0, 0, 210, 22, "F")
        self.set_xy(10, 6)
        self.set_text_color(255, 255, 255)
        self.set_font("Helvetica", "B", 16)
        self.cell(0, 6, "AgriTrue  -  True Cost Accounting Brief")
        self.set_xy(10, 13)
        self.set_font("Helvetica", "", 9)
        self.cell(0, 5, "TEEBAgriFood framework  -  calibrated to FAO SOFA 2024")
        self.ln(16)
        self.set_text_color(0, 0, 0)

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", "I", 7)
        self.set_text_color(*GREY)
        self.multi_cell(
            0, 3.5,
            "Generated by AgriTrue. Figures use Poore & Nemecek (2018) LCA medians and a "
            "social cost of carbon (Rennert et al. 2022). Values are estimates shown with "
            "uncertainty; per-country splits are modelled to match SOFA 2024 aggregates.",
            align="C")


_UNICODE_MAP = {
    "—": "-", "–": "-", "−": "-", "‑": "-",  # dashes / minus
    "≈": "~", "·": "-", "…": "...", "×": "x",
    "‘": "'", "’": "'", "“": '"', "”": '"',
    "₹": "INR ", "€": "EUR ", " ": " ",
}


def _san(text: str) -> str:
    """Make text safe for the latin-1 core PDF font (the briefs use no embedded Unicode font)."""
    text = str(text).replace("**", "")
    for u, a in _UNICODE_MAP.items():
        text = text.replace(u, a)
    return text.encode("latin-1", "replace").decode("latin-1")


def _section(pdf: FPDF, title: str):
    pdf.ln(2)
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(*DARK)
    pdf.cell(0, 7, title, new_x="LMARGIN", new_y="NEXT")
    pdf.set_draw_color(*GREEN)
    pdf.set_line_width(0.6)
    y = pdf.get_y()
    pdf.line(10, y, 200, y)
    pdf.ln(2)
    pdf.set_text_color(0, 0, 0)


def _kpi_row(pdf: FPDF, kpis: list[tuple[str, str]]):
    """Render up to 4 KPI cards in a row."""
    n = len(kpis)
    w = 190 / n
    x0 = 10
    y0 = pdf.get_y()
    for i, (label, value) in enumerate(kpis):
        x = x0 + i * w
        pdf.set_fill_color(245, 247, 246)
        pdf.rect(x, y0, w - 3, 18, "F")
        pdf.set_xy(x + 2, y0 + 2)
        pdf.set_font("Helvetica", "", 7.5)
        pdf.set_text_color(*GREY)
        pdf.multi_cell(w - 6, 3.4, label.upper())
        pdf.set_xy(x + 2, y0 + 9)
        pdf.set_font("Helvetica", "B", 14)
        pdf.set_text_color(*DARK)
        pdf.cell(w - 6, 7, value)
    pdf.set_xy(x0, y0 + 22)
    pdf.set_text_color(0, 0, 0)


def _hbar_chart(pdf: FPDF, rows: list[tuple[str, float]], unit: str, color=GREEN):
    """Draw a horizontal bar chart from (label, value) rows."""
    if not rows:
        return
    max_v = max(abs(v) for _, v in rows) or 1.0
    bar_x = 60
    bar_w_max = 130
    row_h = 7
    pdf.set_font("Helvetica", "", 8.5)
    for label, val in rows:
        y = pdf.get_y()
        pdf.set_text_color(0, 0, 0)
        pdf.set_xy(10, y)
        pdf.cell(48, row_h, label[:30])
        w = bar_w_max * (abs(val) / max_v)
        pdf.set_fill_color(*(RED if val < 0 else color))
        pdf.rect(bar_x, y + 1.2, max(w, 0.4), row_h - 2.4, "F")
        pdf.set_xy(bar_x + w + 2, y)
        pdf.set_text_color(*GREY)
        pdf.cell(30, row_h, f"{val:,.2f} {unit}")
        pdf.ln(row_h)
    pdf.set_text_color(0, 0, 0)


def _new() -> _Brief:
    pdf = _Brief()
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()
    return pdf


