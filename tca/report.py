def true_price_pdf(result: dict) -> bytes:
    """One-pager for a single True Price Calculator result."""
    pdf = _new()
    _section(pdf, f"True price of {result['commodity']}  ({result['mass_kg']:g} kg)")
    hc = result["hidden_cost"]
    _kpi_row(pdf, [
        ("Market price", f"${result['market_price']:.2f}"),
        ("Hidden cost", f"${hc['central']:.2f}"),
        ("True price", f"${result['true_price']:.2f}"),
        ("Hidden : market", f"{result['hidden_to_market_ratio']:.2f}x"),
    ])
    pdf.set_font("Helvetica", "", 9)
    pdf.multi_cell(0, 5,
        f"Hidden-cost uncertainty band: ${hc['low']:.2f} - ${hc['high']:.2f}. "
        f"The market price omits the environmental externalities below, which society "
        f"pays through climate damage, water stress, nutrient pollution and land conversion.")
    pdf.ln(2)
    _section(pdf, "Hidden cost by externality")
    rows = [(k.title(), v["central"]) for k, v in result["components"].items()]
    rows.sort(key=lambda r: r[1], reverse=True)
    _hbar_chart(pdf, rows, "USD")
    return bytes(pdf.output())


def diet_pdf(comparison: dict) -> bytes:
    """One-pager comparing a diet pattern against the EAT-Lancet reference."""
    pdf = _new()
    a, b = comparison["diet_a"], comparison["diet_b"]
    ra, rb = comparison["result_a"], comparison["result_b"]
    _section(pdf, f"Diet true-cost comparison")
    pdf.set_font("Helvetica", "", 9)
    pdf.multi_cell(0, 5, f"{a}  vs  {b}  (annual hidden cost per person)")
    pdf.ln(1)
    _kpi_row(pdf, [
        (f"{a[:18]} hidden cost", f"${ra['total_hidden_cost_usd_yr']:,.0f}/yr"),
        (f"{b[:18]} hidden cost", f"${rb['total_hidden_cost_usd_yr']:,.0f}/yr"),
        ("Difference", f"${comparison['delta_usd_yr']:,.0f}/yr"),
        ("vs reference", f"{comparison['delta_pct']:+.0f}%"),
    ])
    _section(pdf, "Footprint difference (A - reference)")
    _hbar_chart(pdf, [
        ("GHG (kg CO2e/yr)", comparison["ghg_delta_kg_yr"]),
        ("Hidden cost (USD/yr)", comparison["delta_usd_yr"]),
    ], "", color=DARK)
    _section(pdf, f"Top cost contributors - {a}")
    rows = [(f["commodity"], f["hidden_cost_usd_yr"]) for f in ra["foods"][:8]]
    _hbar_chart(pdf, rows, "USD/yr")
    return bytes(pdf.output())


def teeb_study_pdf(study: dict, comparison: dict) -> bytes:
    """One-pager for a localized TEEBAgriFood scenario comparison (B vs A)."""
    pdf = _new()
    a, b = comparison["scenario_a"], comparison["scenario_b"]
    _section(pdf, _san(study["name"]))
    pdf.set_font("Helvetica", "", 9)
    pdf.multi_cell(0, 5, _san(
        f"{study['country']}  -  {b} vs {a}.  Basis: {study['basis']}.\n{study['summary']}"))
    pdf.ln(1)
    def _m(v):  # keep decimals for small (e.g. Billion-USD) magnitudes; integers for large
        return f"${v:,.2f}" if abs(v) < 100 else f"${v:,.0f}"
    _kpi_row(pdf, [
        ("Net societal value change", _m(comparison['delta_net_societal'])),
        ("Farmer's private change", _m(comparison['delta_private'])),
        ("External (society) change", _m(comparison['delta_external'])),
        ("Basis", _san(study["basis"].split("(")[0][:18])),
    ])
    _section(pdf, _san(f"Change in capital flows ({b} - {a})"))
    from tca.teeb_studies import CAPITAL_LABELS
    _hbar_chart(pdf, [
        (_san(CAPITAL_LABELS[c]), comparison["delta_by_capital"][c])
        for c in ("produced", "natural", "human", "social")
    ], "", color=DARK)
    pdf.ln(1)
    pdf.set_font("Helvetica", "I", 7.5)
    pdf.set_text_color(*GREY)
    pdf.multi_cell(0, 3.5, _san(
        f"Source: {study['source']}  Values are taken from the cited report (or derived from its "
        f"published figures) and are adjustable in the app for sensitivity analysis."))
    pdf.set_text_color(0, 0, 0)
    return bytes(pdf.output())


def national_pdf(country: dict, global_anchors: dict) -> bytes:
    """One-pager for a country's hidden-cost profile."""
    pdf = _new()
    _section(pdf, f"National hidden-cost profile - {country['name']}")
    _kpi_row(pdf, [
        ("Total hidden cost", f"${country['hidden_total_busd']:,.0f}bn/yr"),
        ("Share of GDP", f"{country['hc_pct_gdp']*100:.1f}%"),
        ("Agrifood system", country["system"]),
        ("Region", country["region"]),
    ])
    pdf.set_font("Helvetica", "", 9)
    pdf.multi_cell(0, 5,
        f"Global context: agrifood systems carry ~${global_anchors['total_hidden_cost_trillion_usd']:.0f} "
        f"trillion/yr in hidden costs (~{global_anchors['share_of_global_gdp']*100:.0f}% of global GDP), "
        f"~{global_anchors['health_share']*100:.0f}% health-driven (FAO SOFA 2024).")
    pdf.ln(1)
    _section(pdf, "Hidden cost by capital (USD bn / yr)")
    _hbar_chart(pdf, [
        ("Health", country["health_busd"]),
        ("Environmental", country["env_busd"]),
        ("Social", country["social_busd"]),
    ], "bn")
    return bytes(pdf.output())
